import { mkdir, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { join } from "node:path";

const root = process.cwd();
const result = spawnSync("cargo.exe", [
  "test",
  "--manifest-path",
  "src-tauri/Cargo.toml",
  "--lib",
  "github_tracking::tests::v07_r02_production_scheduler_lifecycle_evidence_is_measured",
  "--",
  "--nocapture",
  "--test-threads=1",
], {
  cwd: root,
  encoding: "utf8",
  windowsHide: true,
  maxBuffer: 16 * 1024 * 1024,
});
const output = `${result.stdout ?? ""}\n${result.stderr ?? ""}`;
if (result.status !== 0) throw new Error(`native V07 R02 lifecycle probe failed with exit ${result.status}`);
const marker = "M19_V07_R02_LIFECYCLE_JSON=";
const markerLine = output.split(/\r?\n/).find((line) => line.includes(marker));
if (!markerLine) throw new Error(`native lifecycle probe did not emit ${marker}`);
const evidence = JSON.parse(markerLine.slice(markerLine.indexOf(marker) + marker.length));

const requiredFields = [
  "generationId", "projectId", "requestAcceptedEpoch", "qualifyingObservationId",
  "observationStartEpoch", "observationCompletionEpoch", "workerAdmissionState",
  "workerAdmissionEpoch", "preExistingInFlight", "queueAdmissionOutcome", "resultHealth",
  "validatedAtBefore", "validatedAtAfter", "nextDueEpoch", "freshnessHorizonSeconds",
  "generationResult", "historyRecordingPermitted", "diagnostic",
];
for (const row of evidence.rows) {
  for (const field of requiredFields) {
    if (!(field in row)) throw new Error(`V07 R02 lifecycle row missing ${field}`);
  }
}

const summary = evidence.rows
  .map((row) => `| ${row.generationId} | ${row.projectId} | ${row.qualifyingObservationId} | ${row.preExistingInFlight ? "YES" : "NO"} | ${row.queueAdmissionOutcome} | ${row.resultHealth} | ${row.generationResult} | ${row.historyRecordingPermitted ? "YES" : "NO"} |`)
  .join("\n");
const detail = evidence.rows
  .map((row, index) => `### Row ${index + 1}: ${row.projectId} / generation ${row.generationId}\n\n\`\`\`json\n${JSON.stringify(row, null, 2)}\n\`\`\``)
  .join("\n\n");

const document = `# M19 V07 R02 Tracking Lifecycle Matrix

Generated by \`npm run generate:evidence:v07-r02\` from the native production scheduler lifecycle probe \`github_tracking::tests::v07_r02_production_scheduler_lifecycle_evidence_is_measured\`. The probe calls the same \`SchedulerLifecycleState\` admission, in-flight identity, worker-result, and generation completion transitions used by the production polling loop. Epochs are deterministic test-clock boundaries; diagnostics are sanitized and no credentials or raw response bodies are included.

## Contract

- Schema: \`${evidence.schema}\`
- Worker capacity: ${evidence.workerCapacity}
- Observation execution budget: ${evidence.executionBudgetSeconds}s
- Admission/queue budget: ${evidence.admissionBudgetSeconds}s
- One M19 hard freshness horizon: ${evidence.freshnessHorizonSeconds}s
- Selected scheduler target only: ${evidence.selectedSchedulerTargetSeconds}s
- A generation is completed only by its attached qualifying observation identity. Pre-existing in-flight observations remain unrelated.

## Production scheduler evidence summary

| Generation | Project | Qualifying observation | Pre-existing in-flight | Queue/admission outcome | Result health | Generation result | History permitted |
|---:|---|---:|:---:|---|---|---|:---:|
${summary}

The matrix includes pre-existing in-flight/manual-A protection, independent A/B concurrency, same-project coalescing, saturated four-worker admission, slow changed-HEAD success within the execution budget, and an over-deadline cancellation whose late result cannot authorize history recording.

## Complete lifecycle rows

${detail}
`;

await mkdir(join(root, "docs/H!veAI/evidence"), { recursive: true });
await writeFile(join(root, "docs/H!veAI/evidence/M19_V07_R02_TRACKING_LIFECYCLE_MATRIX.md"), document, "utf8");
console.log("Generated docs/H!veAI/evidence/M19_V07_R02_TRACKING_LIFECYCLE_MATRIX.md");

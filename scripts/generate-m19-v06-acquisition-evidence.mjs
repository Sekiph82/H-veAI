import { mkdir, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { join } from "node:path";

const root = process.cwd();
const result = spawnSync("cargo.exe", [
  "test",
  "--manifest-path",
  "src-tauri/Cargo.toml",
  "--lib",
  "github_integration::tests::v06_production_portfolio_acquisition_evidence_is_measured",
  "--",
  "--nocapture",
  "--test-threads=1",
], {
  cwd: root,
  encoding: "utf8",
  windowsHide: true,
  maxBuffer: 8 * 1024 * 1024,
});
const output = `${result.stdout ?? ""}\n${result.stderr ?? ""}`;
if (result.status !== 0) throw new Error(`native evidence probe failed with exit ${result.status}`);
const markerLine = output.split(/\r?\n/).find((line) => line.includes("M19_V06_EVIDENCE_JSON="));
if (!markerLine) throw new Error("native evidence probe did not emit M19_V06_EVIDENCE_JSON");
const evidence = JSON.parse(markerLine.slice(markerLine.indexOf("M19_V06_EVIDENCE_JSON=") + "M19_V06_EVIDENCE_JSON=".length));
const fields = [
  "projectId", "repository", "branch", "intent", "stage", "resourceKind",
  "cacheBefore", "cacheAfter", "admission", "coalescing", "httpStatus",
  "errorClass", "budgetPrimaryBefore", "budgetPrimaryAfter",
  "budgetOptionalBefore", "budgetOptionalAfter", "fetchedAt", "lastKnownGoodAt",
];
const rows = evidence.rows.map((row, index) => `### Stage ${index + 1}: ${row.repository} / ${row.stage}\n\n\`\`\`json\n${JSON.stringify(row, null, 2)}\n\`\`\``).join("\n\n");
const math = evidence.hourlyMath.map((row) => `| ${row.projects} | ${row.backgroundObservationsPerHour} | ${row.sameHeadHttpStagesPerHour} | ${row.changedHeadHttpStagesPerHour} | ${row.governorAdmittedStagesPerHour} |`).join("\n");
const document = `# M19 V06 GitHub acquisition matrix

Generated by \`npm run generate:evidence:v06\` from the native production orchestration probe \`github_integration::tests::v06_production_portfolio_acquisition_evidence_is_measured\`. The HTTP boundary is a deterministic fixture transport; orchestration, planner, cache classification, and process-wide governor are production code. No credentials or raw response bodies are included.

## Measured portfolio

- Schema: \`${evidence.schema}\`
- Measured navigation portfolio: ${evidence.measuredPortfolio.projects} projects, ${evidence.measuredPortfolio.snapshots} snapshots, ${evidence.measuredPortfolio.primaryRequests} admitted primary stages.
- Process budget: ${evidence.requestBudget.primaryPerHour} primary + ${evidence.requestBudget.optionalPerHour} optional = ${evidence.requestBudget.totalPerHour} requests/hour.
- Required row fields: ${fields.map((field) => `\`${field}\``).join(", ")}.

## Exact hourly tracking math

| Portfolio | Background observations/hour | Same-HEAD HTTP stages/hour | Changed-HEAD HTTP stages/hour | Governor-admitted stages/hour |
|---:|---:|---:|---:|---:|
${math}

The selected project is manually refreshed by explicit project id and is not a portfolio-wide refresh. Background validation is one observation/project/hour; a changed HEAD requires three HTTP stages, and the process-wide governor caps admitted tracking stages at 40/hour.

## Per-stage production-path rows

${rows}
`;
await mkdir(join(root, "docs/H!veAI/evidence"), { recursive: true });
await writeFile(join(root, "docs/H!veAI/evidence/M19_V06_GITHUB_ACQUISITION_MATRIX.md"), document, "utf8");
console.log("Generated docs/H!veAI/evidence/M19_V06_GITHUB_ACQUISITION_MATRIX.md");

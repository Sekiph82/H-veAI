import { mkdir, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { join } from "node:path";

const root = process.cwd();
const result = spawnSync("cargo.exe", [
  "test",
  "--manifest-path",
  "src-tauri/Cargo.toml",
  "--lib",
  "github_integration::tests::v07_production_governed_acquisition_evidence_is_measured",
  "--",
  "--nocapture",
  "--test-threads=1",
], {
  cwd: root,
  encoding: "utf8",
  windowsHide: true,
  maxBuffer: 16 * 1024 * 1024,
});
const output = `${result.stdout ?? ""}\n${result.stderr ?? ""}`;
if (result.status !== 0) throw new Error(`native V07 evidence probe failed with exit ${result.status}`);
const marker = "M19_V07_EVIDENCE_JSON=";
const markerLine = output.split(/\r?\n/).find((line) => line.includes(marker));
if (!markerLine) throw new Error(`native evidence probe did not emit ${marker}`);
const evidence = JSON.parse(markerLine.slice(markerLine.indexOf(marker) + marker.length));

const requiredFields = [
  "projectId", "repository", "branch", "intent", "windowRotationCursor", "rotationPosition",
  "resourceClass", "resourceKind", "cacheBefore", "admission", "owner", "coalescing", "network",
  "httpStatus", "httpStatusClass", "budgetPrimaryBefore", "budgetPrimaryAfter",
  "budgetOptionalBefore", "budgetOptionalAfter", "trackingBudgetBefore", "trackingBudgetAfter",
  "failureClass", "fetchedAt", "validatedAt", "lastKnownGoodAgeSeconds", "presentation",
  "diagnostic", "rateLimit",
];
for (const row of evidence.rows) {
  for (const field of requiredFields) {
    if (!(field in row)) throw new Error(`V07 evidence row missing ${field}`);
  }
}

const detailed = evidence.detailedIntegrationDemand
  .map((row) => `| ${row.intent} | ${row.projects} | ${row.scheduledPrimaryRequests} | ${row.admittedPrimaryRequests} | ${row.scheduledOptionalRequests} | ${row.admittedOptionalRequests} | ${row.scheduledRemoteTrackingRequests} |`)
  .join("\n");
const tracking = evidence.trackingDemand.map((row) =>
  `| ${row.projects} | ${row.background.scheduledObservationsPerHour} | ${row.background.unchangedHeadStagesPerHour} | ${row.background.changedHeadStagesPerHour} | ${row.background.admittedStagesPerHour} | ${row.oneSelectedProject.scheduledObservationsPerHour} | ${row.oneSelectedProject.changedHeadStagesPerHour} | ${row.oneSelectedProject.admittedStagesPerHour} |`,
).join("\n");
const backoff = evidence.failureBackoff
  .map((row) => `| ${row.failure} | ${row.backgroundRetrySeconds} | ${row.selectedRetrySeconds} |`)
  .join("\n");
const rows = evidence.rows
  .map((row, index) => `### Stage ${index + 1}: ${row.repository} / ${row.resourceKind}\n\n\`\`\`json\n${JSON.stringify(row, null, 2)}\n\`\`\``)
  .join("\n\n");

const document = `# M19 V07 GitHub acquisition matrix

Generated by \`npm run generate:evidence:v07\` from the native production-governed acquisition probe \`github_integration::tests::v07_production_governed_acquisition_evidence_is_measured\`. The probe uses the production portfolio orchestration, planner, cache classification, request governor, and navigation context; only the HTTP transport is deterministic and fixture-backed. No credentials or raw response bodies are included.

## Provenance and budgets

- Schema: \`${evidence.schema}\`
- Source: \`${evidence.source}\`
- Measured Navigation window: ${evidence.measuredPortfolio.projects} projects, ${evidence.measuredPortfolio.snapshots} snapshots, ${evidence.measuredPortfolio.networkRequests} network requests.
- Process-wide demand budget: ${evidence.requestBudget.primaryPerHour} primary + ${evidence.requestBudget.optionalPerHour} optional = ${evidence.requestBudget.totalPerHour} requests/hour.
- Every row has the complete V07 schema: ${requiredFields.map((field) => `\`${field}\``).join(", ")}.

## Detailed integration API demand

| Intent | Portfolio | Scheduled primary | Admitted primary | Scheduled optional | Admitted optional | Scheduled tracking |
|---|---:|---:|---:|---:|---:|---:|
${detailed}

Idle is cache-only for detailed resources. Selected and Manual are explicitly scoped to the selected project. Navigation uses fair per-project rotation and reserved primary capacity; optional enrichment is separately bounded.

## Root-TASKS remote tracking demand

| Projects | Background scheduled observations/hour | Background unchanged-HEAD stages/hour | Background changed-HEAD stages/hour | Background admitted stages/hour | One-selected scheduled observations/hour | One-selected changed-HEAD stages/hour | One-selected admitted stages/hour |
|---:|---:|---:|---:|---:|---:|---:|---:|
${tracking}

The scheduler cadence is ${evidence.freshness.backgroundCadenceSeconds}s for background projects and ${evidence.freshness.selectedCadenceSeconds}s for the selected project. A changed HEAD has ${evidence.freshness.changedHeadStages} sequential bounded stages. M19 uses a ${evidence.freshness.backgroundHardHorizonSeconds}s portfolio hard validation horizon and a ${evidence.freshness.selectedHardHorizonSeconds}s selected target horizon; failed validation never advances validation freshness.

## Failure/backoff evidence

| Consecutive failure | Background retry seconds | Selected retry seconds |
|---:|---:|---:|
${backoff}

The retry schedule is monotonic, bounded, resets on a CURRENT observation, and never retries a background failure more aggressively than its normal hourly cadence. Governor budget wait is a budget state and does not create a five-minute retry loop.

## Per-stage production-governed rows

${rows}
`;

await mkdir(join(root, "docs/H!veAI/evidence"), { recursive: true });
await writeFile(join(root, "docs/H!veAI/evidence/M19_V07_GITHUB_ACQUISITION_MATRIX.md"), document, "utf8");
console.log("Generated docs/H!veAI/evidence/M19_V07_GITHUB_ACQUISITION_MATRIX.md");
